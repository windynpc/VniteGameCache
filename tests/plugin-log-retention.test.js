const assert = require('assert')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { __test } = require('../src/VniteGameCache.Plugin/index.js')

assert.strictEqual(__test.maximumLogTotalBytes, 500 * 1024 * 1024)
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'vgc-log-retention-'))
try {
  const plugin = path.join(root, 'plugin')
  const logs = path.join(root, 'logs')
  fs.mkdirSync(plugin)
  fs.mkdirSync(logs)
  const oldest = path.join(plugin, 'vnite-game-cache.jsonl')
  const copy = path.join(logs, 'game.robocopy.log')
  const latest = path.join(logs, '20261021.jsonl')
  fs.writeFileSync(oldest, 'a'.repeat(60))
  fs.writeFileSync(copy, 'b'.repeat(60))
  fs.writeFileSync(latest, 'c'.repeat(20))
  fs.utimesSync(oldest, new Date(0), new Date(0))
  fs.utimesSync(copy, new Date(1000), new Date(1000))
  const unrelated = path.join(logs, 'settings.json')
  fs.writeFileSync(unrelated, 'keep')
  const external = path.join(root, 'external')
  fs.mkdirSync(external)
  fs.writeFileSync(path.join(external, '20200101.jsonl'), 'keep')
  fs.symlinkSync(external, path.join(logs, 'linked'), process.platform === 'win32' ? 'junction' : 'dir')
  __test.trimLogs([plugin, logs, logs], 100)
  assert.ok(!fs.existsSync(oldest))
  assert.ok(fs.existsSync(copy))
  assert.strictEqual(fs.readFileSync(latest, 'utf8'), 'c'.repeat(20))
  assert.strictEqual(fs.readFileSync(unrelated, 'utf8'), 'keep')
  assert.strictEqual(fs.readFileSync(path.join(external, '20200101.jsonl'), 'utf8'), 'keep')

  // Preserve the new event while reclaiming an oversized daily segment.
  const current = path.join(plugin, '20261021.plugin.jsonl')
  fs.writeFileSync(current, 'x'.repeat(90))
  __test.appendLog(current, 'new event\n', [plugin], 95, 95)
  assert.strictEqual(fs.readFileSync(current, 'utf8'), 'new event\n')
  assert.strictEqual(fs.readdirSync(plugin).length, 1)
  __test.appendLog(current, 'x'.repeat(101), [plugin], 100, 95)
  const total = fs.readdirSync(plugin).reduce((sum, file) => sum + fs.statSync(path.join(plugin, file)).size, 0)
  assert.ok(total <= 100)
  // A failed write must not break plugin actions.
  assert.doesNotThrow(() => __test.appendLog(path.join(unrelated, '20261021.jsonl'), 'event\n', [plugin], 100))
} finally {
  fs.rmSync(root, { recursive: true, force: true })
}
