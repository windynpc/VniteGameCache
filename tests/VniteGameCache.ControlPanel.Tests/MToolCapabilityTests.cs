using System.Reflection;
using VniteGameCache.ControlPanel;

namespace VniteGameCache.ControlPanel.Tests;

public sealed class MToolCapabilityTests
{
    [Fact]
    public void Reports_verified_batch_legacy_exe_and_unrecognized_batch_separately()
    {
        var root = Path.Combine(Path.GetTempPath(), "vgc-mtool-capability-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(root);
        try
        {
            var batch = Path.Combine(root, "与工具一同启动.bat");
            File.WriteAllText(batch, "REM This file is automatically generated by the MTool.\r\n\"E:\\MTool\\loaders\\inject.exe\" \"D:\\Game\\Game.exe\" \"E:\\MTool\\loaders\\PythonHook64.dll\"\r\n");
            Assert.Equal("bat", DetectKind(root));

            File.WriteAllText(Path.Combine(root, "MTool_Game.exe"), "fixture");
            Assert.Equal("bat", DetectKind(root));
            File.Delete(Path.Combine(root, "MTool_Game.exe"));

            File.Delete(batch);
            File.WriteAllText(Path.Combine(root, "MTool_Game.exe"), "fixture");
            Assert.Equal("exe", DetectKind(root));

            File.Delete(Path.Combine(root, "MTool_Game.exe"));
            File.WriteAllText(batch, "echo unrelated");
            Assert.Equal("unverified-bat", DetectKind(root));

            File.Delete(batch);
            Assert.Null(DetectKind(root));
        }
        finally
        {
            Directory.Delete(root, recursive: true);
        }
    }

    [Fact]
    public void Reports_translation_candidate_and_mtool_fallback_without_changing_launch_mode()
    {
        var root = Path.Combine(Path.GetTempPath(), "vgc-translation-capability-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(root);
        try
        {
            var game = Path.Combine(root, "Game.exe");
            File.WriteAllText(game, "fixture");
            Assert.Equal("未发现其他候选", DescribeTranslation(root, game));

            File.WriteAllText(Path.Combine(root, "MTool_Game.exe"), "fixture");
            Assert.Equal("MTool_Game.exe 可用（启动待验证）", DescribeTranslation(root, game));

            File.WriteAllText(Path.Combine(root, "Game_CHS.exe"), "fixture");
            Assert.Equal("候选 Game_CHS.exe（启动待验证）", DescribeTranslation(root, game));
        }
        finally
        {
            Directory.Delete(root, recursive: true);
        }
    }

    [Fact]
    public void Translation_status_prefers_cached_files_over_source_only_candidate()
    {
        var root = Path.Combine(Path.GetTempPath(), "vgc-translation-cache-" + Guid.NewGuid().ToString("N"));
        var source = Path.Combine(root, "source");
        var cache = Path.Combine(root, "cache");
        Directory.CreateDirectory(source);
        Directory.CreateDirectory(cache);
        try
        {
            var game = Path.Combine(source, "Game.exe");
            File.WriteAllText(game, "fixture");
            File.WriteAllText(Path.Combine(source, "Game_CHS.exe"), "fixture");
            File.WriteAllText(Path.Combine(cache, "Game.exe"), "fixture");

            Assert.Equal("未发现其他候选", DescribeTranslation(source, game, cache));

            File.WriteAllText(Path.Combine(cache, "MTool_Game.exe"), "fixture");
            Assert.Equal("MTool_Game.exe 可用（启动待验证）", DescribeTranslation(source, game, cache));
        }
        finally
        {
            Directory.Delete(root, recursive: true);
        }
    }

    private static string? DetectKind(string root)
    {
        var mainForm = typeof(UiFeatureRegistry).Assembly.GetType("VniteGameCache.ControlPanel.MainForm")!;
        var detector = mainForm.GetMethod("DetectMToolArtifact", BindingFlags.NonPublic | BindingFlags.Static)!;
        var result = detector.Invoke(null, [new[] { root }]);
        return result?.GetType().GetProperty("Kind")?.GetValue(result) as string;
    }

    private static string DescribeTranslation(string root, string executablePath, string cacheRoot = "")
    {
        var mainForm = typeof(UiFeatureRegistry).Assembly.GetType("VniteGameCache.ControlPanel.MainForm")!;
        var detector = mainForm.GetMethod("DescribeTranslationCapability", BindingFlags.NonPublic | BindingFlags.Static)!;
        return (string)detector.Invoke(null, [root, cacheRoot, executablePath])!;
    }
}
